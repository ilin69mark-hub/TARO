-- Посев app_config для настроек, которые код читает, но строки не было.
--
-- Зачем: ключи ab.price_month, offers.winback, spreads.seasonal были в
-- allowlist и в панели, но не сеялись ни одной миграцией. Поэтому они молча
-- работали «в выключенном состоянии»: A/B-цена всегда control/0, winback всегда
-- 0/0, сезонная ротация — no-op. Само по себе это безопасно (код обрабатывает
-- отсутствие строки), но в панели вместо значения показывалась пустая
-- textarea, и администратор должен был угадать схему JSON.
--
-- Теперь у каждой настройки есть стартовое значение: выключенное, но с полями
-- и комментариями. Включение остаётся решением владельца.
--
-- Обратная совместимость: все значения выключены, поведение не меняется.
-- auth.handoff_enabled НЕ трогаем — он уже посеян миграцией 040 и остаётся false.

-- A/B-цена месячного тарифа. split — процент на тестовую цену (0..100).
-- До решения владельца о 299 vs 349 (E09) остаётся выключенным.
INSERT INTO app_config (key, value) VALUES
  ('ab.price_month', '{"enabled": false, "control": 299, "test": 349, "split": 50}')
ON CONFLICT (key) DO NOTHING;

-- Winback: предложение вернувшемуся. pct — процент аудитории, попадающей в
-- предложение. Выключено до решения по цене/рекламе.
INSERT INTO app_config (key, value) VALUES
  ('offers.winback', '{"enabled": false, "pct": 20}')
ON CONFLICT (key) DO NOTHING;

-- Сезонные окна: массив {code, from, to} в формате YYYY-MM-DD. Пустой массив =
-- ротация выключена. Расклады fullmoon/newyear существуют, но is_active=false.
INSERT INTO app_config (key, value) VALUES
  ('spreads.seasonal', '[]')
ON CONFLICT (key) DO NOTHING;

-- Кризисный текст: видит человек вместо толкования, если вопрос попал под
-- фильтр. Номера телефона нет сознательно (решение владельца 2026-09-30:
-- развлекательный сервис, не служба помощи) — текст советует местные
-- экстренные службы. Совпадает с константой в readings.go:38, чтобы админка
-- показывала ровно то, что отдаёт код.
INSERT INTO app_config (key, value) VALUES
  ('safety.crisis', jsonb_build_object('crisis_resource_text',
    'Если ты думаешь о самоповреждении или о том, что можешь причинить себе вред, обратись в местные экстренные службы или на официальную линию кризисной поддержки своей страны. Если есть непосредственная опасность, не оставайся один. Карты подождут.'))
ON CONFLICT (key) DO NOTHING;
